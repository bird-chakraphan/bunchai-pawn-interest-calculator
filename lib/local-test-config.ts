// B01 deliberately supports only this local stack. Hosted/release targets need review.
export const LOCAL_TEST_SUPABASE_URL = "http://127.0.0.1:55321"

export function assertLocalTestUrl(url: string): void {
    if (url !== LOCAL_TEST_SUPABASE_URL) {
        throw new Error("สภาพแวดล้อมทดสอบนี้เชื่อมต่อได้เฉพาะฐานข้อมูลทดสอบในเครื่อง")
    }
}

export function assertLocalTestConfiguration(env: Record<string, string | undefined>): void {
    if (env.NEXT_PUBLIC_BUNCHAI_ENVIRONMENT !== "local-test") {
        throw new Error("B01 requires NEXT_PUBLIC_BUNCHAI_ENVIRONMENT=local-test")
    }

    assertLocalTestUrl(env.NEXT_PUBLIC_SUPABASE_URL?.trim() ?? "")

    if (!env.NEXT_PUBLIC_SUPABASE_ANON_KEY?.trim() || !env.SUPABASE_SERVICE_ROLE_KEY?.trim()) {
        throw new Error("B01 requires keys generated by the local Supabase stack")
    }

    if (env.PAYMENTS_ENABLED !== "false") {
        throw new Error("B01 requires PAYMENTS_ENABLED=false")
    }

    for (const name of ["INTERNAL_SYNC_SECRET", "OMISE_SECRET_KEY", "LINE_CHANNEL_ACCESS_TOKEN", "LINE_GROUP_ID"]) {
        if (env[name]?.trim()) {
            throw new Error(`B01 does not allow ${name}`)
        }
    }
}
